"""Guided Caesar practice using the real bundled engine; no hosted accounts."""
import json
from pathlib import Path
from playwright.sync_api import sync_playwright, expect


def check():
    out = Path('dist/caesar-lesson-checks'); out.mkdir(exist_ok=True)
    with sync_playwright() as p:
        browser = p.chromium.launch()
        context = browser.new_context()
        # Delay real engine requests so reset-during-check is deterministic.
        context.add_init_script('''const originalPost = Worker.prototype.postMessage;
            Worker.prototype.postMessage = function(data, ...args) {
              if (String(data?.id).startsWith('chat-')) {
                setTimeout(() => originalPost.call(this, data, ...args), 150);
              } else originalPost.call(this, data, ...args);
            };''')
        page = context.new_page()
        errors = []
        page.on('pageerror', lambda e: errors.append(str(e)))
        page.goto('http://localhost:8502')
        expect(page.locator('#identify')).to_be_enabled(timeout=90000)
        page.locator('#manual-tab').click()
        page.locator('#message').fill('Keep the existing lab draft.')
        page.locator('#key').fill('9')
        page.locator('#encrypt').click()
        expect(page.locator('#status')).to_have_text('Encryption complete.')
        result = page.locator('#result').text_content()
        page.locator('#hash-tab').click()
        page.locator('#hash-text').fill('Keep the hash experiment.')
        page.locator('#learn-tab').click()
        expect(page.locator('#learn-content')).to_be_visible()
        integrity = page.evaluate("localStorage.getItem('ciphercraft.learn.hash-integrity.v1')")
        page.locator('#learn-lesson-select').select_option('caesar')
        expect(page.locator('#cs-progress')).to_have_text('0 of 3 steps complete')
        expect(page.locator('#integrity-lesson')).to_be_hidden()
        expect(page.locator('#password-lesson')).to_be_hidden()
        expect(page.locator('#cs-step-1-tab')).to_be_disabled()
        expect(page.locator('#cs-trace')).to_be_hidden()
        page.locator('#cs-letter').fill('A')
        page.locator('#cs-letter').press('Enter')
        expect(page.locator('#cs-feedback-0')).to_contain_text('Try again')
        expect(page.locator('#cs-next-0')).to_be_disabled()
        page.locator('#cs-hint-0').click()
        expect(page.locator('#cs-hint-text-0')).to_contain_text('first move lands on Z')
        page.locator('#cs-hint-0').click()
        expect(page.locator('#cs-hint-text-0')).to_contain_text('wraps to A')
        page.locator('#cs-letter').fill('b')
        page.locator('#cs-check-0').click()
        expect(page.locator('#cs-trace')).to_be_visible()
        page.locator('#cs-step-0-tab').focus()
        page.keyboard.press('ArrowRight')
        expect(page.locator('#cs-step-1-tab')).to_be_focused()
        expect(page.locator('#cs-step-1')).to_be_visible()
        # Once loaded, the lesson and shared cipher engine work without a network.
        context.set_offline(True)
        page.locator('#cs-word').fill('ABC')
        page.locator('#cs-check-1').click()
        expect(page.locator('#cs-feedback-1')).to_contain_text('Try again')
        page.locator('#cs-word').fill('cat')
        page.locator('#cs-check-1').click()
        expect(page.locator('#cs-word-mapping')).to_be_visible()
        page.locator('#cs-next-1').click()
        expect(page.locator('#cs-title-2')).to_be_focused()
        page.locator('#cs-key').fill('3')
        page.locator('#cs-phrase').fill('Meet me at noon.')
        page.locator('#cs-check-2').click()
        expect(page.locator('#cs-feedback-2')).to_contain_text('Try again')
        page.locator('#cs-key').fill('7')
        page.locator('#cs-phrase').fill('Meet at dawn.')
        page.locator('#cs-check-2').click()
        expect(page.locator('#cs-feedback-2')).to_contain_text('key is correct')
        page.locator('#cs-phrase').fill('Meet me at noon!')
        page.locator('#cs-check-2').click()
        expect(page.locator('#cs-complete')).to_be_visible()
        expect(page.locator('#cs-complete-title')).to_be_focused()
        expect(page.locator('#cs-progress')).to_have_text('3 of 3 steps complete')
        for width in (320, 390, 768, 1440):
            page.set_viewport_size({'width': width, 'height': 950})
            assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'), width
            page.screenshot(path=str(out/f'completed-{width}.png'), full_page=True)
        saved = json.loads(page.evaluate("localStorage.getItem('ciphercraft.learn.caesar.v1')"))
        assert saved == dict(step=2, letter='B', word='CAT', key=7, phrase='MEET ME AT NOON')
        page.locator('#cs-open-tools').click()
        expect(page.locator('#message')).to_have_value('Keep the existing lab draft.')
        expect(page.locator('#key')).to_have_value('9')
        expect(page.locator('#result')).to_have_text(result)
        page.locator('#hash-tab').click()
        expect(page.locator('#hash-text')).to_have_value('Keep the hash experiment.')
        page.locator('#learn-tab').click()
        assert page.evaluate("localStorage.getItem('ciphercraft.learn.hash-integrity.v1')") == integrity
        page.locator('#learn-lesson-select').select_option('password')
        expect(page.locator('#password-lesson')).to_be_visible()
        expect(page.locator('#caesar-lesson')).to_be_hidden()
        page.locator('#learn-lesson-select').select_option('caesar')
        expect(page.locator('#cs-complete')).to_be_visible()
        context.set_offline(False)
        page.reload()
        expect(page.locator('#identify')).to_be_enabled(timeout=90000)
        page.locator('#learn-tab').click()
        expect(page.locator('#learn-lesson-select')).to_have_value('caesar')
        expect(page.locator('#cs-complete')).to_be_visible()
        page.locator('#cs-reset').click()
        page.locator('#cs-reset-no').click()
        expect(page.locator('#cs-complete')).to_be_visible()
        page.locator('#cs-reset').click()
        page.locator('#cs-reset-yes').click()
        expect(page.locator('#cs-progress')).to_have_text('0 of 3 steps complete')
        page.locator('#cs-letter').fill('B')
        page.locator('#cs-check-0').click()
        page.locator('#cs-reset').click()
        page.locator('#cs-reset-yes').click()
        page.wait_for_timeout(350)  # Past the deliberately delayed worker response.
        expect(page.locator('#cs-progress')).to_have_text('0 of 3 steps complete')
        expect(page.locator('#cs-feedback-0')).to_have_text('')
        expect(page.locator('#cs-next-0')).to_be_disabled()
        page.evaluate("localStorage.setItem('ciphercraft.learn.caesar.v1',JSON.stringify({step:2,letter:'X',word:'CAT',key:7,phrase:'MEET ME AT NOON'}))")
        page.reload()
        expect(page.locator('#identify')).to_be_enabled(timeout=90000)
        page.locator('#learn-tab').click()
        expect(page.locator('#cs-progress')).to_have_text('0 of 3 steps complete')
        expect(page.locator('#cs-step-1-tab')).to_be_disabled()
        blocked = browser.new_context()
        blocked.add_init_script("Storage.prototype.getItem=()=>{throw new DOMException('Unavailable','SecurityError')};Storage.prototype.setItem=()=>{throw new DOMException('Unavailable','SecurityError')};")
        second = blocked.new_page()
        second.goto('http://localhost:8502')
        expect(second.locator('#identify')).to_be_enabled(timeout=90000)
        second.locator('#learn-tab').click()
        second.locator('#learn-lesson-select').select_option('caesar')
        expect(second.locator('#cs-storage')).to_contain_text('storage is unavailable')
        second.locator('#cs-letter').fill('B')
        second.locator('#cs-check-0').click()
        expect(second.locator('#cs-next-0')).to_be_enabled()
        blocked.close()
        assert not errors, errors
        browser.close()
    print('Caesar lesson checks passed: shared engine, hints, wrong/right answers, offline, persistence, reset race, keyboard, responsive layout and existing-work isolation.')


if __name__ == '__main__':
    check()
