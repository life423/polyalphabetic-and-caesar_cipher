"""Guided lesson, evidence downloads, feedback, progress and lab isolation."""
import argparse
import hashlib
from pathlib import Path

from playwright.sync_api import expect, sync_playwright


def check(url, screenshots):
    output = Path(screenshots)
    output.mkdir(parents=True, exist_ok=True)
    with sync_playwright() as playwright:
        browser = playwright.chromium.launch()
        context = browser.new_context()
        page = context.new_page()
        errors = []
        page.on('pageerror', lambda error: errors.append(str(error)))
        page.goto(url)
        expect(page.locator('#identify')).to_be_enabled(timeout=90000)
        page.locator('#manual-tab').click()
        page.locator('#message').fill('Keep all my existing work.')
        page.locator('#key').fill('7')
        page.locator('#encrypt').click()
        expect(page.locator('#status')).to_have_text('Encryption complete.')
        result = page.locator('#result').text_content()
        page.locator('#play-tab').click()
        page.locator('#guess-A').fill('T')
        page.locator('#hash-tab').click()
        page.locator('#hash-text').fill('Keep this hash input too.')
        page.locator('#hash-text-run').click()
        expected_digest = hashlib.sha256(b'Keep this hash input too.').hexdigest()
        expect(page.locator('#hash-text-digest')).to_have_text(expected_digest)
        page.locator('#learn-tab').click()
        expect(page.locator('#learn-content')).to_be_visible()
        expect(page.locator('#learn-step-1-tab')).to_be_disabled()
        page.locator('#learn-check-1').click()
        expect(page.locator('#learn-feedback-1')).to_contain_text('Choose an answer')
        page.locator('[name="learn-quiz-1"][value="random"]').check()
        page.locator('#learn-check-1').click()
        expect(page.locator('#learn-feedback-1')).to_contain_text('Try again')
        expect(page.locator('#learn-next-1')).to_be_disabled()
        page.locator('[name="learn-quiz-1"][value="same"]').check()
        page.locator('#learn-check-1').click()
        expect(page.locator('#learn-feedback-1')).to_contain_text('Correct')
        for width in (320, 390, 768, 1440):
            page.set_viewport_size({'width': width, 'height': 1000})
            assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'), width
            page.screenshot(path=str(output / f'lesson-{width}.png'), full_page=True)
        # All bundled lesson evidence is already available; next steps work offline.
        context.set_offline(True)
        page.locator('#learn-next-1').click()
        expect(page.locator('#learn-quiz-2')).to_be_hidden()
        page.locator('#learn-experiment').click()
        expect(page.locator('#learn-example-difference')).to_contain_text('129 of 256')
        page.locator('[name="learn-quiz-2"][value="exact"]').check()
        page.locator('#learn-check-2').click()
        expect(page.locator('#learn-feedback-2')).to_contain_text('Try again')
        page.locator('[name="learn-quiz-2"][value="varies"]').check()
        page.locator('#learn-check-2').click()
        page.locator('#learn-next-2').click()
        expect(page.locator('#learn-check-evidence')).to_be_disabled()
        for name in ['keeper-log', 'channel-note', 'beacon-order']:
            page.locator('#learn-hash-' + name).click()
        expect(page.locator('#learn-match-keeper-log')).to_contain_text('Matches')
        expect(page.locator('#learn-match-channel-note')).to_contain_text('Matches')
        expect(page.locator('#learn-match-beacon-order')).to_contain_text('Mismatch')
        expect(page.locator('#learn-check-evidence')).to_be_enabled()
        page.locator('#learn-check-evidence').click()
        expect(page.locator('#learn-evidence-feedback')).to_contain_text('Choose a file and a conclusion')
        page.locator('[name="learn-found"][value="keeper-log"]').check()
        page.locator('[name="learn-reason"][value="changed"]').check()
        page.locator('#learn-check-evidence').click()
        expect(page.locator('#learn-complete')).to_be_hidden()
        expect(page.locator('#learn-evidence-feedback')).to_contain_text('Look again')
        page.locator('[name="learn-found"][value="beacon-order"]').check()
        page.locator('[name="learn-reason"][value="attacker"]').check()
        page.locator('#learn-check-evidence').click()
        expect(page.locator('#learn-evidence-feedback')).to_contain_text('cannot tell you who')
        page.locator('#learn-hint').click()
        expect(page.locator('#learn-hint-text')).to_be_visible()
        page.locator('[name="learn-reason"][value="changed"]').check()
        page.locator('#learn-check-evidence').click()
        expect(page.locator('#learn-complete')).to_be_visible()
        expect(page.locator('#learn-progress')).to_contain_text('3 of 3 steps complete')
        for width in (320, 390, 768, 1440):
            page.set_viewport_size({'width': width, 'height': 1000})
            assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'), width
            page.screenshot(path=str(output / f'evidence-{width}.png'), full_page=True)
        for name in ['keeper-log', 'channel-note', 'beacon-order']:
            with page.expect_download() as event:
                page.get_by_role('button', name='Save ' + name + '.txt', exact=True).click()
            download = event.value
            assert download.suggested_filename == name + '.txt'
            assert Path(download.path()).read_bytes() == (Path(__file__).resolve().parents[1] / 'static/learn/evidence' / (name + '.txt')).read_bytes()
        # Opening the lab must never inject evidence into or erase prior lab work.
        page.locator('#learn-open-lab').click()
        expect(page.locator('#hash-text')).to_have_value('Keep this hash input too.')
        expect(page.locator('#hash-text-digest')).to_have_text(expected_digest)
        page.locator('#hash-back-lesson').click()
        expect(page.locator('#learn-complete')).to_be_visible()
        page.locator('#manual-tab').click()
        expect(page.locator('#message')).to_have_value('Keep all my existing work.')
        expect(page.locator('#result')).to_have_text(result)
        page.locator('#play-tab').click()
        expect(page.locator('#guess-A')).to_have_value('T')
        context.set_offline(False)
        page.reload()
        page.locator('#learn-tab').click()
        expect(page.locator('#learn-complete')).to_be_visible()
        expect(page.locator('#learn-actual-beacon-order')).to_have_text(hashlib.sha256((Path(__file__).resolve().parents[1] / 'static/learn/evidence/beacon-order.txt').read_bytes()).hexdigest())
        page.locator('#learn-reset').click()
        page.locator('#learn-reset-no').click()
        expect(page.locator('#learn-complete')).to_be_visible()
        page.locator('#learn-reset').click()
        page.locator('#learn-reset-yes').click()
        expect(page.locator('#learn-progress')).to_contain_text('0 of 3')
        expect(page.locator('#learn-step-0')).to_be_visible()
        expect(page.locator('#learn-step-1-tab')).to_be_disabled()
        page.locator('#play-tab').click()
        expect(page.locator('#guess-A')).to_have_value('T')
        # A failed cipher engine and unavailable storage do not prevent learning.
        separate = browser.new_context()
        separate.route('**/worker.js', lambda route: route.abort())
        separate.add_init_script("Storage.prototype.setItem=()=>{throw new DOMException('blocked','SecurityError')}")
        independent = separate.new_page()
        independent.goto(url)
        independent.locator('#learn-tab').click()
        expect(independent.locator('#learn-content')).to_be_visible()
        expect(independent.locator('#learn-storage')).to_contain_text('storage is unavailable')
        independent.locator('[name="learn-quiz-1"][value="same"]').check()
        independent.locator('#learn-check-1').click()
        expect(independent.locator('#learn-next-1')).to_be_enabled()
        # Asset failures recover without reloading or touching the other workflows.
        failure = browser.new_context()
        failure.route('**/learn/evidence/*.txt', lambda route: route.abort())
        retry = failure.new_page()
        retry.goto(url)
        retry.locator('#learn-tab').click()
        expect(retry.locator('#learn-error')).to_be_visible()
        failure.unroute('**/learn/evidence/*.txt')
        retry.locator('#learn-retry').click()
        expect(retry.locator('#learn-content')).to_be_visible()
        corrupt = browser.new_context()
        corrupt.add_init_script('''localStorage.setItem('ciphercraft.learn.hash-integrity.v1','{"step":99,"passed1":true,"passed2":true,"confirmed":true,"quiz1":"bad","hashed":["bogus"]}')''')
        bad = corrupt.new_page()
        bad.goto(url)
        bad.locator('#learn-tab').click()
        expect(bad.locator('#learn-step-0')).to_be_visible()
        expect(bad.locator('#learn-complete')).to_be_hidden()
        expect(bad.locator('#learn-progress')).to_contain_text('0 of 3')
        # Resetting during a digest must not resurrect old observations.
        delayed = browser.new_context()
        delayed.add_init_script('''localStorage.setItem('ciphercraft.learn.hash-integrity.v1',JSON.stringify({step:2,quiz1:'same',quiz2:'varies',passed1:true,passed2:true,experiment:true,hashed:[]}))''')
        race = delayed.new_page()
        race.goto(url)
        race.locator('#learn-tab').click()
        expect(race.locator('#learn-step-2')).to_be_visible()
        race.evaluate('''()=>{window.realDigest=crypto.subtle.digest.bind(crypto.subtle);
            Object.defineProperty(crypto.subtle,'digest',{configurable:true,value:(...args)=>new Promise(resolve=>{
              window.releaseObservation=()=>resolve(window.realDigest(...args));})});}''')
        race.locator('#learn-hash-keeper-log').click()
        race.locator('#learn-reset').click()
        race.locator('#learn-reset-yes').click()
        race.evaluate('window.releaseObservation();delete crypto.subtle.digest')
        expect(race.locator('#learn-progress')).to_contain_text('0 of 3')
        expect(race.locator('#learn-actual-keeper-log')).to_have_text('Not calculated yet')
        assert not errors, errors
        browser.close()
    print('Learn passed: lesson feedback, real SHA-256 experiment, altered evidence, exact downloads, progress/recovery, offline use and isolation at four widths.')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--url', default='http://localhost:8502')
    parser.add_argument('--screenshots', default='dist/learn-checks')
    args = parser.parse_args()
    check(args.url, args.screenshots)
